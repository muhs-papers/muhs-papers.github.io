// Usage: node scripts/materialize-papers.js <staging directory> <legacy staging directory>
// Render the manually reviewed ledger, preserving every input page once per scan.
const fs = require("node:fs"), path = require("node:path"), crypto = require("node:crypto");
const { PDFDocument } = require("pdf-lib");
const root=path.join(__dirname,".."), dir=process.argv[2];
global.window={}; require("../data.js");
const subjects=new Map(window.MUHS_DATA.subjects.map(s=>[s.id,s.name]));
const rows=JSON.parse(fs.readFileSync(path.join(dir,"inventory.json")));
const expected=[...fs.readFileSync(path.join(root,"HANDOVER.md"),"utf8").matchAll(/^\| `[^`]+` \| `[^`]+` \| `([\w-]+)` \| [\d,.]+ [MK]B \|$/gm)].map(m=>m[1]);
const decisions=fs.readFileSync(path.join(__dirname,"review-decisions.tsv"),"utf8").split(/\r?\n/).filter(l=>l&&!l.startsWith("#"));
async function main(){
  if(decisions.length!==170||expected.length!==rows.length)throw Error("Incomplete review ledger");
  const records=[];
  const legacyDir=process.argv[3], legacy=JSON.parse(fs.readFileSync(path.join(legacyDir,"inventory.json")));
  for(const original of window.MUHS_DATA.defaultPapers){
    const r=legacy.find(row=>"gdrive_"+row.id===original.id);
    const input=fs.readFileSync(path.join(legacyDir,r.id+".pdf"));
    if(crypto.createHash("sha256").update(input).digest("hex")!==r.sha256)throw Error("Legacy source hash mismatch: "+r.id);
    const pilot=window.MUHS_DATA.hostedPapers.find(p=>p.id===original.id);
    if(pilot){if(!input.equals(fs.readFileSync(path.join(root,pilot.url))))throw Error("Legacy pilot mismatch");continue;}
    const collection=original.title.includes("Summer & Winter");
    const fileName=`legacy-${r.id}.pdf`, url=`papers/${r.subject}/${fileName}`;
    fs.mkdirSync(path.join(root,"papers",r.subject),{recursive:true});fs.writeFileSync(path.join(root,url),input);
    records.push({...original,...(collection?{catalogueGroup:"Multi-year collection",year:null,session:null}:{}),
      kind:"site",url,fileType:"application/pdf",fileName,fileSize:input.length,sourceId:r.id});
  }
  for(const [index,line] of decisions.entries()){
    const [key,term,layout,...note]=line.split(" ");
    const r=rows[index], subject=subjects.get(r.subject);
    if(+key!==index||r.id!==expected[index]||!subject)throw Error("Inventory order changed at "+index);
    const input=fs.readFileSync(path.join(dir,r.id+".pdf"));
    if(crypto.createHash("sha256").update(input).digest("hex")!==r.sha256)throw Error("Source hash mismatch: "+r.id);
    const spans=layout.split(",").map(x=>x.split(":").map(Number));
    const pdf=await PDFDocument.load(input,{ignoreEncryption:true,updateMetadata:false});
    const total=pdf.getPageCount(), session=term[0]==="S"?"Summer":term[0]==="W"?"Winter":null;
    const year=session?Number(term.slice(1)):null;
    if(spans[0][0]!==1)throw Error("Incomplete page range");
    for(const [j,[start,n]] of spans.entries()){
      const end=spans[j+1]?spans[j+1][0]-1:total;
      if(start>end||end>total||![0,1,2].includes(n))throw Error("Invalid range: "+line);
      let bytes=input;
      if(spans.length>1){
        const output=await PDFDocument.create({updateMetadata:false});
        const pages=await output.copyPages(pdf,Array.from({length:end-start+1},(_,k)=>start+k-1));
        pages.forEach(page=>output.addPage(page));bytes=Buffer.from(await output.save());
      }
      const group=term==="A"?"Multi-year collection":term==="U"?"Exam session unverified":null;
      const stem=(session?`${session.toLowerCase()}-${year}`:term==="A"?"collection":"undated")+(n?`-paper-${n}`:"");
      const fileName=index===7?"summer-2025-paper-1-cbme.pdf":`${stem}-${r.id.slice(-7)}-${start}.pdf`;
      const url=`papers/${r.subject}/${fileName}`;
      fs.mkdirSync(path.join(root,"papers",r.subject),{recursive:true});
      fs.writeFileSync(path.join(root,url),bytes);
      let variant=note.join(" ");
      if(variant==="2019 / old schemes")variant=j<2?"2019 scheme":"Old scheme";
      const title=[subject,n?"Paper "+n:"",session?`${session} ${year}`:group,variant].filter(Boolean).join(" — ");
      records.push({id:`gdrive_${r.id}`+(spans.length>1?`_p${start}`:""),subjectId:r.subject,session,year,
        paperNumber:n||null,title,kind:"site",...(group?{catalogueGroup:group}:{}),
        fileType:"application/pdf",fileName,fileSize:bytes.length,url,sourceId:r.id,sourcePages:[start,end],
        addedAt:"2026-11-25T00:00:00Z"});
    }
  }
  fs.writeFileSync(path.join(root,"hosted-papers.js"),"// Generated by scripts/materialize-papers.js from reviewed page ranges.\nwindow.MUHS_DATA.hostedPapers.push(\n"+records.map(r=>"  "+JSON.stringify(r)).join(",\n")+"\n);\n");
  console.log(`Materialized ${records.length+2} catalogue entries, including ${legacy.length} returning catalogue IDs.`);
}
main().catch(err=>{console.error(err);process.exitCode=1});
